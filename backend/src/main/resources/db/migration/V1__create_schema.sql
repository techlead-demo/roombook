CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    role  VARCHAR(20)  NOT NULL
);

CREATE TABLE rooms (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(50) NOT NULL UNIQUE,
    capacity INT         NOT NULL CHECK (capacity > 0),
    active   BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE room_equipment (
    room_id   BIGINT      NOT NULL REFERENCES rooms (id),
    equipment VARCHAR(30) NOT NULL,
    PRIMARY KEY (room_id, equipment)
);

CREATE TABLE bookings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    BIGINT                      NOT NULL REFERENCES rooms (id),
    user_id    BIGINT                      NOT NULL REFERENCES users (id),
    title      VARCHAR(100)                NOT NULL,
    start_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    end_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT bookings_end_after_start CHECK (end_at > start_at)
);

CREATE INDEX bookings_room_start_idx ON bookings (room_id, start_at);
